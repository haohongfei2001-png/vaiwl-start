/** A local observation of one explicitly bounded native Project panel.
 * This carries neither account/workspace ownership nor confirmed membership. */
import { parseConversationUrl, parseProjectUrl } from '../../domain/ids.js';
import { bounded, exact } from '../../shared/protocol.js';

export interface ProjectCandidate {
  state: 'candidate';
  relationBasis: 'linked-native-panel';
  projectId: string;
  nativeTitle: string;
  canonicalUrl: string;
  members: Array<{ conversationId: string; nativeTitle: string; canonicalUrl: string }>;
}

/** Called by the background worker only after authenticating the isolated
 * collector and its current browser document/route. The isolation key and
 * observation time are generated by that worker, never accepted from the page. */
export function parseLocalProjectCandidate(value: unknown, sourceHref: string): ProjectCandidate {
  exact(value, ['state', 'relationBasis', 'projectId', 'nativeTitle', 'canonicalUrl', 'members']);
  const route = parseProjectUrl(sourceHref);
  if (!route || value.state !== 'candidate' || value.relationBasis !== 'linked-native-panel' || value.projectId !== route.projectId || value.canonicalUrl !== route.canonicalUrl) throw Error('INVALID_MESSAGE');
  bounded(value.nativeTitle, 200);
  if (value.nativeTitle !== value.nativeTitle.trim() || !Array.isArray(value.members) || value.members.length > 200) throw Error('INVALID_MESSAGE');
  const seen = new Set<string>();
  const members = value.members.map((member: unknown) => {
    exact(member, ['conversationId', 'nativeTitle', 'canonicalUrl']);
    bounded(member.nativeTitle, 200);
    const identity = parseConversationUrl(member.canonicalUrl);
    if (!identity || identity.conversationId !== member.conversationId || identity.canonicalUrl !== member.canonicalUrl || member.nativeTitle !== member.nativeTitle.trim() || seen.has(identity.conversationId)) throw Error('INVALID_MESSAGE');
    seen.add(identity.conversationId);
    return { conversationId: identity.conversationId, nativeTitle: member.nativeTitle, canonicalUrl: identity.canonicalUrl };
  });
  return { state: 'candidate', relationBasis: 'linked-native-panel', projectId: route.projectId, nativeTitle: value.nativeTitle, canonicalUrl: route.canonicalUrl, members };
}
