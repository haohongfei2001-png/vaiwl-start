/** A local observation of one explicitly bounded native Project panel.
 * This carries neither account/workspace ownership nor confirmed membership. */
import { parseConversationUrl, parseProjectUrl, projectIdFromContainer } from '../../domain/ids.js';
import { bounded, exact } from '../../shared/protocol.js';
import { instant } from '../../domain/time.js';
import type { NativeMemberTime, NativeProjectTimeOrder } from './native-time.js';

export interface ProjectCandidate {
  state: 'candidate';
  relationBasis: 'linked-native-panel' | 'explicit-project-links' | 'labelled-sidebar-project' | 'native-project-page';
  projectId: string;
  nativeTitle: string | null;
  canonicalUrl: string;
  members: Array<{ conversationId: string; nativeTitle: string | null; canonicalUrl: string; sourceUrl?: string; time?: NativeMemberTime }>;
  timeOrder?: NativeProjectTimeOrder;
}

/** Called by the background worker only after authenticating the isolated
 * collector and its current browser document/route. The isolation key and
 * observation time are generated by that worker, never accepted from the page. */
export function parseLocalProjectCandidate(value: unknown, sourceHref: string): ProjectCandidate {
  exact(value, ['state', 'relationBasis', 'projectId', 'nativeTitle', 'canonicalUrl', 'members'], ['timeOrder']);
  const route = parseProjectUrl(sourceHref), project = parseProjectUrl(value.canonicalUrl);
  const nativeSource = sourceHref === 'https://chatgpt.com/' || sourceHref === 'https://chatgpt.com/projects'
    || sourceHref.startsWith('https://chatgpt.com/') && !!(route || parseConversationUrl(sourceHref));
  const explicit = value.relationBasis === 'explicit-project-links' || value.relationBasis === 'labelled-sidebar-project';
  const titleOnly = value.relationBasis === 'native-project-page';
  if (!nativeSource || !project || value.state !== 'candidate' || value.projectId !== project.projectId || value.canonicalUrl !== project.canonicalUrl
    || !(explicit || (value.relationBasis === 'linked-native-panel' || titleOnly) && route?.projectId === project.projectId)) throw Error('INVALID_MESSAGE');
  const title = (input: unknown, nullable: boolean): string | null => {
    if (nullable && input === null) return null;
    bounded(input, 200); if (input !== input.trim()) throw Error('INVALID_MESSAGE'); return input;
  };
  const nativeTitle = title(value.nativeTitle, explicit);
  if (!Array.isArray(value.members) || value.members.length > 200 || explicit && value.members.length === 0 || titleOnly && value.members.length !== 0) throw Error('INVALID_MESSAGE');
  const seen = new Set<string>();
  const members = value.members.map((member: unknown) => {
    exact(member, ['conversationId', 'nativeTitle', 'canonicalUrl'], ['sourceUrl', 'time']);
    const memberTitle = title(member.nativeTitle, explicit);
    const identity = parseConversationUrl(member.canonicalUrl);
    if (!identity || identity.conversationId !== member.conversationId || identity.canonicalUrl !== member.canonicalUrl || seen.has(identity.conversationId)) throw Error('INVALID_MESSAGE');
    const source = parseConversationUrl(member.sourceUrl);
    if (explicit && (!source || source.conversationId !== identity.conversationId || projectIdFromContainer(source.containerHint) !== project.projectId)
      || !explicit && member.sourceUrl !== undefined) throw Error('INVALID_MESSAGE');
    seen.add(identity.conversationId);
    let time: NativeMemberTime | undefined;
    if (member.time !== undefined) {
      exact(member.time, ['kind', 'semantic', 'at']);
      if (value.relationBasis !== 'linked-native-panel' || member.time.kind !== 'native-updated' || member.time.semantic !== 'conversation-last-activity' || instant(member.time.at) === null) throw Error('INVALID_MESSAGE');
      time = { kind: 'native-updated', semantic: 'conversation-last-activity', at: member.time.at };
    }
    return { conversationId: identity.conversationId, nativeTitle: memberTitle, canonicalUrl: identity.canonicalUrl, ...(explicit ? { sourceUrl: member.sourceUrl as string } : {}), ...(time ? { time } : {}) };
  });
  let timeOrder: NativeProjectTimeOrder | undefined;
  if (value.timeOrder !== undefined) {
    const order = value.timeOrder;
    exact(order, ['semantic', 'direction', 'coverage', 'pinned', 'manual', 'memberIds']);
    if (value.relationBasis !== 'linked-native-panel' || order.semantic !== 'conversation-last-activity' || order.direction !== 'descending' || order.coverage !== 'complete' || order.pinned !== false || order.manual !== false
      || !Array.isArray(order.memberIds) || order.memberIds.length < 2 || order.memberIds.length !== members.length || new Set(order.memberIds).size !== members.length || order.memberIds.some((id: unknown) => typeof id !== 'string' || !seen.has(id))) throw Error('INVALID_MESSAGE');
    timeOrder = { semantic: 'conversation-last-activity', direction: 'descending', coverage: 'complete', pinned: false, manual: false, memberIds: [...order.memberIds] };
  }
  return { state: 'candidate', relationBasis: value.relationBasis, projectId: project.projectId, nativeTitle, canonicalUrl: project.canonicalUrl, members, ...(timeOrder ? { timeOrder } : {}) };
}
